/**
 * 유통업체의 배송 권역 배열(delivery_regions)과 식당의 요청 권역(rfqRegion)이 일치하는지 판정.
 * 예: delivery_regions = ["충북 청주시 흥덕구"], rfqRegion = "충북 청주시 흥덕구 복대동" -> true
 */
export function isRegionMatched(
  supplierRegions: string[] | null | undefined,
  rfqRegion: string | null | undefined
): boolean {
  if (!supplierRegions || supplierRegions.length === 0 || !rfqRegion) return false;

  const normalize = (s: string) =>
    s
      .replace(/특별시|광역시|특별자치시/g, "")
      .replace(/\s+/g, " ")
      .trim()
      .toLowerCase();

  const target = normalize(rfqRegion);

  return supplierRegions.some((reg) => {
    const candidate = normalize(reg);
    if (!candidate) return false;
    return target === candidate || target.startsWith(candidate) || target.includes(candidate) || candidate.includes(target);
  });
}
